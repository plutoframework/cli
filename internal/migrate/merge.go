package migrate

import (
	"bytes"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path"
	"path/filepath"
)

const generatedHeader = "// Code generated by Pluto; DO NOT EDIT."

func (w *Workspace) markPristineTest(name string) {
	if w.pristineTests == nil {
		w.pristineTests = map[string]bool{}
	}

	w.pristineTests[name] = true
}

// mergeEdited carries user edits of a scaffold file onto the next scaffold
// with a three-way merge (scaffold the user started from, the user's file, the
// next scaffold). It returns true when the merge was clean; conflicts leave
// the file untouched so the caller reports a manual item. Generated files are
// never merged: edits to them are drift, not authorship.
func mergeEdited(
	w *Workspace,
	name string,
	current, want []byte,
	bases [][]byte,
	profile string,
) bool {
	if bytes.HasPrefix(want, []byte(generatedHeader)) ||
		bytes.HasPrefix(current, []byte(generatedHeader)) {
		return false
	}

	for _, base := range bases {
		merged, ok := threeWay(current, base, want)
		if !ok || !validMerge(name, merged) {
			continue
		}

		reason := "your edits were merged into the " + profile +
			" scaffold (clean three-way merge)"

		if bytes.Equal(merged, current) {
			reason = "your edits kept: the " + profile +
				" scaffold did not change this file"
		} else if err := w.Write(name, merged); err != nil {
			return false
		}

		w.Note(Item{
			Path:   name,
			Line:   firstDifference(current, base),
			Reason: reason,
			Action: "review the result; pluto vet and the architecture " +
				"check run after apply",
		})

		return true
	}

	return false
}

// validMerge fails closed: merged Go must still parse.
func validMerge(name string, merged []byte) bool {
	if path.Ext(name) != ".go" {
		return true
	}

	_, err := parser.ParseFile(
		token.NewFileSet(),
		name,
		merged,
		parser.AllErrors,
	)

	return err == nil
}

// threeWay runs git merge-file on temporary copies. Any failure, including a
// missing git, reports no clean merge.
func threeWay(current, base, next []byte) ([]byte, bool) {
	directory, err := os.MkdirTemp("", "pluto-merge-")
	if err != nil {
		return nil, false
	}

	defer os.RemoveAll(directory)

	files := []string{}

	for index, data := range [][]byte{current, base, next} {
		file := filepath.Join(directory, string(rune('a'+index)))
		if err := os.WriteFile(file, data, 0o600); err != nil {
			return nil, false
		}

		files = append(files, file)
	}

	command := exec.Command(
		"git", "merge-file", "-p",
		"-L", "yours", "-L", "scaffold", "-L", "next",
		files[0], files[1], files[2],
	)

	command.Env = append(os.Environ(), "GIT_CONFIG_GLOBAL=/dev/null")

	var out bytes.Buffer

	command.Stdout = &out

	if err := command.Run(); err != nil {
		return nil, false
	}

	return out.Bytes(), true
}
