func requiredPrimitives(m project.Manifest) []string {
	if m.Frontend.UI != "shadcn" {
		return nil
	}

	needed := map[string]string{}

	if m.Frontend.Auth {
		for _, name := range []string{"button", "input", "label"} {
			needed[name] = name
		}
	}

	for _, c := range m.Frontend.Components {
		names := []string{c.Kind}
		if c.Kind == "registry" {
			names = c.Primitives
		}

		switch c.Kind {
		case "form":
			names = []string{"button", "input", "label"}
		case "dialog":
			names = []string{"button", "dialog"}
		}

		for _, name := range names {
			needed[name] = name
		}
	}

	return sortedKeys(needed)
}

func profile(m project.Manifest) []byte {
	return []byte(
		fmt.Sprintf(
			"# Owned profile marker; changing library requires explicit migration.\nui = %q\ntemplate_version = 1\n",
			m.Frontend.UI,
		),
	)
}

func Contracts(root string, m project.Manifest) error {
	if err := m.Validate(); err != nil {
		return err
	}

	if m.Frontend == nil {
		return nil
	}

	for name, expected := range map[string][]byte{
		"pluto-ui.toml": profile(m),
	} {
		path, err := project.SafePath(
			root,
			filepath.Join(m.Frontend.Directory, name),
		)
		if err != nil {
			return err
		}

		actual, err := os.ReadFile(path)
		if err != nil {
			return err
		}

		if !bytes.Equal(actual, expected) {
			return fmt.Errorf(
				"frontend UI profile differs; changing config alone cannot migrate components",
			)
		}
	}

	path, err := project.SafePath(
		root,
		filepath.Join(m.Frontend.Directory, "src/app/catalog.gen.ts"),
	)
	if err != nil {
		return err
	}

	actual, err := os.ReadFile(path)
	if err != nil {
		return err
	}

	expected, err := catalog(m)
	if err != nil {
		return err
	}

	if !bytes.Equal(actual, expected) {
		return fmt.Errorf(
			"frontend catalog modified or metadata drifted; restore it before generation",
		)
	}

	return nil
}

func (p *Plan) profile() error {
	f := p.Manifest.Frontend

	p.Files[filepath.Join(f.Directory, "pluto-ui.toml")] = profile(p.Manifest)
	if f.UI == "shadcn" {
		config := map[string]any{
			"$schema": "https://ui.shadcn.com/schema.json",
			"style":   "new-york",
			"rsc":     false,
			"tsx":     true,
			"tailwind": map[string]any{
				"config":       "",
				"css":          "src/app/styles.css",
				"baseColor":    "neutral",
				"cssVariables": true,
				"prefix":       "",
			},
			"iconLibrary": "lucide",
			"aliases": map[string]string{
				"components": "@/shared",
				"ui":         "@/shared/ui",
				"lib":        "@/shared/lib",
				"utils":      "@/shared/lib/utils",
				"hooks":      "@/shared/hooks",
			},
		}

		data, err := jsonBytes(config)
		if err != nil {
			return err
		}

		p.Files[filepath.Join(f.Directory, "components.json")] = data
		if err := p.addTemplate("src/shared/lib/utils.ts.tmpl"); err != nil {
			return err
		}

		license, err := sources.ReadFile("profiles/shadcn/LICENSE.txt")
		if err != nil {
			return err
		}

		p.Files[filepath.Join(f.Directory, "licenses/shadcn-MIT.txt")] = license
	}

	return p.primitives("", project.Manifest{})
}

func (p *Plan) primitives(root string, previous project.Manifest) error {
	old := map[string]bool{}

	if previous.Frontend != nil {
		for _, name := range requiredPrimitives(previous) {
			old[name] = true
		}
	}

	for _, name := range requiredPrimitives(p.Manifest) {
		path := filepath.Join(
			p.Manifest.Frontend.Directory,
			"src/shared/ui",
			name+".tsx",
		)
		if old[name] {
			// Existing primitives belong to the application, including edits.
			safe, err := project.SafePath(root, path)
			if err != nil {
				return err
			}

			if _, err := os.Stat(safe); err != nil {
				return fmt.Errorf(
					"required component %s missing: %w",
					path,
					err,
				)
			}

			continue
		}

		data, err := sources.ReadFile("profiles/shadcn/" + name + ".tsx")
		if err != nil {
			return err
		}

		p.Files[path] = data
	}

	return nil
}

func catalog(m project.Manifest) ([]byte, error) {
	var out strings.Builder
	out.WriteString(
		"// Generated by Pluto. Feature implementations remain application-owned.\n",
	)
	out.WriteString("import type { ComponentType } from \"react\";\n")

	if m.Frontend.Auth {
		out.WriteString(
			"import { AuthPage } from \"@/features/session/public\";\nexport { SessionProvider as SessionBoundary } from \"@/features/session/public\";\nexport const AuthEntry: ComponentType | null = AuthPage;\n",
		)
	} else {
		out.WriteString(
			"export { Fragment as SessionBoundary } from \"react\";\nexport const AuthEntry: ComponentType | null = null;\n",
		)
	}

	for _, c := range m.Frontend.Components {
		fmt.Fprintf(
			&out,
			"import { %s } from \"@/features/%s/public\";\n",
			symbol(c.Name),
			c.Name,
		)
	}

	out.WriteString(
		"export const components: { name: string; Component: ComponentType }[] = [\n",
	)

	for _, c := range m.Frontend.Components {
		fmt.Fprintf(
			&out,
			"  { name: %q, Component: %s },\n",
			c.Name,
			symbol(c.Name),
		)
	}

	out.WriteString("];\n")

	return []byte(out.String()), nil
}

func (p *Plan) catalog() error {
	data, err := catalog(p.Manifest)
	if err != nil {
		return err
	}

	p.Files[filepath.Join(p.Manifest.Frontend.Directory, "src/app/catalog.gen.ts")] = data

	return nil
}

func (p *Plan) auth() error {
	for _, name := range []string{
		"src/features/session/types.ts.tmpl", "src/features/session/queries.ts.tmpl",
		"src/features/session/mutations.ts.tmpl", "src/features/session/provider.tsx.tmpl",
		"src/features/session/public.ts.tmpl", "src/features/session/forms/AuthForm.tsx.tmpl",
		"src/features/session/pages/AuthPage.tsx.tmpl", "src/features/session/mutations.test.tsx.tmpl",
	} {
		if err := p.addTemplate(name); err != nil {
			return err
		}
	}

	return nil
}

func (p *Plan) mergePackage(root string, previous project.Manifest) error {
	name := filepath.Join(p.Manifest.Frontend.Directory, "package.json")

	path, err := project.SafePath(root, name)
	if err != nil {
		return err
	}

	old, err := os.ReadFile(path)
	if err != nil {
		return err
	}

	var pkg map[string]json.RawMessage
	if err := json.Unmarshal(old, &pkg); err != nil {
		return err
	}

	if pkg == nil {
		return fmt.Errorf("package.json must contain an object")
	}

	sections := map[string]map[string]string{}

	for _, section := range []string{"dependencies", "devDependencies"} {
		current := map[string]string{}
		if raw := pkg[section]; len(raw) > 0 {
			if err := json.Unmarshal(raw, &current); err != nil {
				return err
			}

			if current == nil {
				return fmt.Errorf(
					"package.json %s must contain an object",
					section,
				)
			}
		}

		sections[section] = current
	}

	before, after := dependencies(previous), dependencies(p.Manifest)

	for _, section := range []string{"dependencies", "devDependencies"} {
		current := sections[section]

		for name, version := range after[section] {
			if _, exists := before[section][name]; exists {
				continue
			}

			for other, entries := range sections {
				if other != section {
					if _, exists := entries[name]; exists {
						return fmt.Errorf(
							"dependency %s conflicts: declare %s in %s rather than %s before generation",
							name,
							version,
							section,
							other,
						)
					}
				}
			}

			if existing, exists := current[name]; exists &&
				existing != version {
				return fmt.Errorf(
					"dependency %s conflicts: need %s, found %s; review manually",
					name,
					version,
					existing,
				)
			}

			current[name] = version
		}

		pkg[section], err = json.Marshal(current)
		if err != nil {
			return err
		}
	}

	p.Files[name], err = jsonBytes(pkg)
	if err != nil {
		return err
	}

	p.Previous[name] = old

	return nil
}
