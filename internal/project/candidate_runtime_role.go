package project

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	frameworkTable = regexp.MustCompile(
		`(?im)^\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?"?` +
			`(pluto_[a-z0-9_]+)"?`,
	)
	grantMarker = regexp.MustCompile(
		`(?m)^-- pluto-grant (\S+) (\S+)$`,
	)
)

// ProposeRuntimeRoleMigration returns the migration that creates and grants
// the declared [database] runtime_role. The role is least privilege: it never
// owns a table, bypasses nothing, and cannot UPDATE or DELETE append-only
// tables. It is created NOLOGIN; the deployment enables login and sets the
// credential out of band, so no secret is ever written to a migration.
// Tables already granted by an earlier migration are skipped, so the proposal
// is empty once everything is covered. taken holds files already proposed in
// the same change so numbering stays unique.
func ProposeRuntimeRoleMigration(
	root string,
	m Manifest,
	taken map[string][]byte,
) (map[string][]byte, error) {
	role := m.Database.RuntimeRole
	if role == "" {
		return nil, nil
	}

	number, err := nextMigrationNumber(root, m)
	if err != nil {
		return nil, err
	}

	for path := range taken {
		match := migrationFilePrefix.FindStringSubmatch(
			filepath.Base(path),
		)
		if match == nil {
			continue
		}

		if value, err := strconv.Atoi(match[1]); err == nil &&
			value >= number && value < 99 {
			number = value + 1
		}
	}

	if number >= 99 {
		return nil, fmt.Errorf(
			"no free migration number below 099 for the runtime role",
		)
	}

	granted, framework, err := scanRuntimeRoleState(root, role)
	if err != nil {
		return nil, err
	}

	var tables []grantTarget

	for _, table := range m.Tables {
		tables = append(tables, grantTarget{
			name:       table.Name,
			appendOnly: table.AppendOnly,
		})
	}

	for _, name := range framework {
		tables = append(tables, grantTarget{name: name})
	}

	if index, ok := m.MemberIndexOf(); ok {
		tables = append(tables, grantTarget{
			name:     index.ViewName(),
			readOnly: true,
		})
	}

	sort.Slice(tables, func(i, j int) bool {
		return tables[i].name < tables[j].name
	})

	var missing []grantTarget

	for _, table := range tables {
		if !granted[table.name] {
			missing = append(missing, table)
		}
	}

	if len(missing) == 0 {
		return nil, nil
	}

	path := fmt.Sprintf("db/migrations/%03d_runtime_role.sql", number)

	return map[string][]byte{
		path: []byte(runtimeRoleSQL(role, missing)),
	}, nil
}

type grantTarget struct {
	name       string
	appendOnly bool

	// readOnly is a generated view the runtime role may only read.
	readOnly bool
}

// scanRuntimeRoleState reads migrations on disk for tables already granted to
// the role and for framework-owned (pluto_*) tables the runtime also needs.
func scanRuntimeRoleState(
	root, role string,
) (map[string]bool, []string, error) {
	entries, err := os.ReadDir(filepath.Join(root, "db/migrations"))
	if err != nil {
		return nil, nil, err
	}

	granted := map[string]bool{}
	seen := map[string]bool{}

	var framework []string

	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".sql") ||
			reservedMigration(entry.Name()) {
			continue
		}

		data, err := os.ReadFile(
			filepath.Join(root, "db/migrations", entry.Name()),
		)
		if err != nil {
			return nil, nil, err
		}

		for _, match := range grantMarker.FindAllStringSubmatch(
			string(data), -1,
		) {
			if match[1] == role {
				granted[match[2]] = true
			}
		}

		for _, match := range frameworkTable.FindAllStringSubmatch(
			string(data), -1,
		) {
			if !seen[match[1]] {
				seen[match[1]] = true
				framework = append(framework, match[1])
			}
		}
	}

	return granted, framework, nil
}

// reservedMigration reports numbers from 099 up, which the framework owns and
// which run after any role migration this file proposes.
func reservedMigration(name string) bool {
	match := migrationFilePrefix.FindStringSubmatch(name)
	if match == nil {
		return false
	}

	number, err := strconv.Atoi(match[1])

	return err == nil && number >= 99
}

func runtimeRoleSQL(role string, targets []grantTarget) string {
	var sql strings.Builder

	fmt.Fprintf(
		&sql,
		`-- Generated by pluto: least-privilege runtime role %[1]s.
-- The application must connect as this role, never as a table owner or
-- superuser, or row-level security does not apply. The role is created
-- NOLOGIN: enable login and set its credential in the deployment, for
-- example ALTER ROLE %[1]s LOGIN PASSWORD '...'.
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '%[1]s') THEN
        CREATE ROLE %[1]s NOLOGIN;
    END IF;
END
$$;
ALTER ROLE %[1]s NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;
GRANT USAGE ON SCHEMA public TO %[1]s;
`,
		role,
	)

	for _, target := range targets {
		privileges := "SELECT, INSERT, UPDATE, DELETE"
		if target.appendOnly {
			privileges = "SELECT, INSERT"
		}

		if target.readOnly {
			privileges = "SELECT"
		}

		fmt.Fprintf(
			&sql,
			`
-- pluto-grant %[1]s %[2]s
REVOKE ALL ON %[2]s FROM %[1]s;
GRANT %[3]s ON %[2]s TO %[1]s;
`,
			role,
			target.name,
			privileges,
		)
	}

	return sql.String()
}

// candidateRuntimeRoleGuard renders the startup check that refuses to run as
// a role that would bypass row-level security. There is no override: a
// development database needs the same non-owner role as production.
func candidateRuntimeRoleGuard(m Manifest) []byte {
	names := make([]string, len(m.Tables))
	for index, table := range m.Tables {
		names[index] = strconv.Quote(table.Name)
	}

	return []byte(strings.ReplaceAll(
		strings.ReplaceAll(
			candidateRuntimeRoleGuardSource,
			"{{TABLES}}",
			strings.Join(names, ", "),
		),
		"{{ROLE}}",
		strconv.Quote(m.Database.RuntimeRole),
	))
}

const candidateRuntimeRoleGuardSource = `package postgres

import (
	"context"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5/pgxpool"
)

// runtimeTables are the declared tables whose isolation depends on row-level
// security. Generated; edit pluto.toml instead.
var runtimeTables = []string{{{TABLES}}}

// runtimeRole is the declared [database] runtime_role, or empty when the
// manifest only requires a non-bypassing, non-owner role.
const runtimeRole = {{ROLE}}

// VerifyRuntimeRole refuses to start when the connected role would bypass
// row-level security: a superuser, BYPASSRLS, an owner of (or member of the
// owner role of) a declared table, or any role other than the declared
// runtime_role. It also fails when a declared table lacks forced row-level
// security. Fail closed; there is no override.
func VerifyRuntimeRole(ctx context.Context, pool *pgxpool.Pool) error {
	if pool == nil {
		return errors.New("runtime role check requires a pool")
	}

	var (
		current     string
		superuser   bool
		bypassRLS   bool
	)

	if err := pool.QueryRow(
		ctx,
		"SELECT current_user::text, rolsuper, rolbypassrls "+
			"FROM pg_roles WHERE rolname = current_user",
	).Scan(&current, &superuser, &bypassRLS); err != nil {
		return errors.New("runtime role check failed")
	}

	if runtimeRole != "" && current != runtimeRole {
		return fmt.Errorf(
			"database role %q is not the declared runtime_role %q",
			current,
			runtimeRole,
		)
	}

	if superuser || bypassRLS {
		return fmt.Errorf(
			"database role %q bypasses row-level security", current,
		)
	}

	for _, table := range runtimeTables {
		var enabled, forced, owner bool

		if err := pool.QueryRow(
			ctx,
			"SELECT c.relrowsecurity, c.relforcerowsecurity, "+
				"pg_has_role(current_user, c.relowner, 'USAGE') "+
				"FROM pg_class c WHERE c.oid = to_regclass(quote_ident($1))",
			table,
		).Scan(&enabled, &forced, &owner); err != nil {
			return fmt.Errorf("declared table %q is not visible", table)
		}

		if owner {
			return fmt.Errorf(
				"database role %q owns table %q; connect as a non-owner "+
					"runtime role",
				current,
				table,
			)
		}

		if !enabled || !forced {
			return fmt.Errorf(
				"table %q lacks forced row-level security", table,
			)
		}
	}

	return nil
}
`
