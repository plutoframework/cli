var migrationFilePrefix = regexp.MustCompile(`^(\d+)_`)

// ProposeTableMigrations returns new migration files that give declared
// tables the forced row-level security policy and append-only triggers that
// ARCH612 requires. A table whose existing migrations already satisfy the
// check gets nothing. Applied migrations are never touched: proposals take the
// next free number and are meant to be reviewed and committed like any other
// migration. Tables that no migration creates yet are an error, since a policy
// cannot precede its table.
func ProposeTableMigrations(
	root string,
	m Manifest,
) (map[string][]byte, error) {
	proposals := map[string][]byte{}

	next, err := nextMigrationNumber(root, m)
	if err != nil {
		return nil, err
	}

	tables := append([]Table(nil), m.Tables...)
	sort.Slice(
		tables,
		func(i, j int) bool {
			return tables[i].ID() < tables[j].ID()
		},
	)

	for _, table := range tables {
		cfg := sqlcheck.Config{
			Root:       root,
			SchemaDirs: []string{"db/migrations"},
			Tables: []sqlcheck.Table{{
				Name:         table.Name,
				Group:        table.Group,
				TenantColumn: table.TenantColumn,
				AppendOnly:   table.AppendOnly,
				TenantRoot:   table.TenantRoot,
			}},
			Lookups: sqlcheckLookupsOf(m, table),
		}

		found, err := sqlcheck.CheckMigrations(cfg)
		if err != nil {
			return nil, err
		}

		if len(found) == 0 {
			continue
		}

		for _, diagnostic := range found {
			if strings.Contains(diagnostic.Message, "is not created by") ||
				strings.Contains(diagnostic.Message, "no tenant column") {
				return nil, fmt.Errorf(
					"table %s: %s",
					table.ID(),
					diagnostic.Message,
				)
			}
		}

		path := fmt.Sprintf(
			"db/migrations/%03d_rls_%s.sql",
			next,
			table.Name,
		)
		next++

		proposals[path] = []byte(
			tableMigrationSQL(table) + lookupMigrationSQL(m, table) +
				memberIndexSQL(m, table),
		)
		proposals[downMigrationPath(path)] = []byte(
			memberIndexDownSQL(m, table) + lookupDownSQL(m, table) +
				tableDownSQL(table),
		)
	}

	return proposals, nil
}

func sqlcheckLookupsOf(m Manifest, table Table) []sqlcheck.Lookup {
	var lookups []sqlcheck.Lookup

	for _, lookup := range sqlcheckLookups(m) {
		if lookup.Table == table.Name {
			lookups = append(lookups, lookup)
		}
	}

	return lookups
}

// lookupMigrationSQL renders the declared lookups of a tenant root table. The
// policy admits SELECT of the single row whose key equals a setting that only
// generated lookup code sets, for the duration of one transaction. Row-level
// security cannot limit columns, so the generated lookup reads only the
// security-invoker view, which exposes just the declared columns.
func lookupMigrationSQL(m Manifest, table Table) string {
	var sql strings.Builder

	sql.WriteString(tenantIndexMigrationSQL(m, table))

	for _, lookup := range m.allLookups() {
		if lookup.Table != table.Name {
			continue
		}

		fmt.Fprintf(
			&sql,
			`
-- Generated by pluto: lookup %[1]s resolves one %[2]s row by %[3]s.
DROP POLICY IF EXISTS %[4]s ON %[2]s;
CREATE POLICY %[4]s ON %[2]s FOR SELECT
    USING (%[3]s%[8]s = current_setting('%[5]s', true));
CREATE OR REPLACE VIEW %[6]s WITH (security_invoker = true) AS
    SELECT %[7]s FROM %[2]s;
`,
			lookup.ID,
			table.Name,
			lookup.Key,
			lookup.PolicyName(),
			lookup.Setting(),
			lookup.ViewName(),
			strings.Join(lookup.Columns, ", "),
			lookup.cast(),
		)
	}

	return sql.String()
}

// lookupDownSQL reverses lookupMigrationSQL; it runs before the table's own
// down statements so the policy and view are gone before RLS is disabled.
func lookupDownSQL(m Manifest, table Table) string {
	var sql strings.Builder

	sql.WriteString(tenantIndexDownSQL(m, table))

	for _, lookup := range m.allLookups() {
		if lookup.Table != table.Name {
			continue
		}

		fmt.Fprintf(
			&sql,
			"DROP VIEW IF EXISTS %s;\nDROP POLICY IF EXISTS %s ON %s;\n",
			lookup.ViewName(), lookup.PolicyName(), table.Name,
		)
	}

	return sql.String()
}

// memberIndexSQL renders the subject-to-organizations read that auth events
// declare on the memberships table. The policy admits SELECT of the rows of
// the one subject named by a transaction-local setting that only the
// generated hook code sets from a live verified session. Row-level security
// cannot limit columns, so the hook reads only the security-invoker view,
// which exposes the organization id of currently active memberships.
func memberIndexSQL(m Manifest, table Table) string {
	index, ok := m.MemberIndexOf()
	if !ok || index.Table != table.Name {
		return ""
	}

	return fmt.Sprintf(
		`
-- Generated by pluto: [auth.events] resolves the organizations of a verified
-- subject. Only generated hook code sets %[5]s.
DROP POLICY IF EXISTS %[3]s ON %[1]s;
CREATE POLICY %[3]s ON %[1]s FOR SELECT
    USING (%[2]s = current_setting('%[5]s', true));
CREATE OR REPLACE VIEW %[4]s WITH (security_invoker = true) AS
    SELECT %[6]s::text AS tenant_id FROM %[1]s%[7]s;
`,
		table.Name,
		index.Subject,
		index.PolicyName(),
		index.ViewName(),
		index.Setting(),
		index.Tenant,
		memberIndexActive(m),
	)
}

// memberIndexActive is the active-membership predicate of [memberships], so
// a suspended member is not resolved to its organization.
func memberIndexActive(m Manifest) string {
	column := m.Memberships.ActiveColumn
	if column == "" {
		return ""
	}

	if len(m.Memberships.ActiveValues) == 0 {
		return " WHERE " + column + " IS TRUE"
	}

	values := make([]string, len(m.Memberships.ActiveValues))
	for index, value := range m.Memberships.ActiveValues {
		values[index] = "'" + value + "'"
	}

	return " WHERE " + column + "::text = ANY (ARRAY[" +
		strings.Join(values, ", ") + "])"
}

func memberIndexDownSQL(m Manifest, table Table) string {
	index, ok := m.MemberIndexOf()
	if !ok || index.Table != table.Name {
		return ""
	}

	return fmt.Sprintf(
		"DROP VIEW IF EXISTS %s;\nDROP POLICY IF EXISTS %s ON %s;\n",
		index.ViewName(), index.PolicyName(), table.Name,
	)
}

// nextMigrationNumber is one past the highest number below the reserved range
// on disk or recorded in [migrations.framework], so a proposal never lands on
// a number the framework owns even when that file is not rendered yet.
func nextMigrationNumber(root string, m Manifest) (int, error) {
	entries, err := os.ReadDir(filepath.Join(root, "db/migrations"))
	if err != nil {
		return 0, err
	}

	highest := 0

	for _, number := range m.Migrations.Framework {
		if value, err := strconv.Atoi(number); err == nil && value > highest {
			highest = value
		}
	}

	for _, entry := range entries {
		match := migrationFilePrefix.FindStringSubmatch(entry.Name())
		if match == nil {
			continue
		}

		number, err := strconv.Atoi(match[1])
		if err == nil && number > highest && number < 99 {
			highest = number
		}
	}

	if highest+1 >= 99 {
		return 0, fmt.Errorf(
			"no free migration number below 099 for table policies",
		)
	}

	return highest + 1, nil
}

// downMigrationPath places the reversal of a generated migration beside the
// others in db/down, under the same file name.
func downMigrationPath(up string) string {
	return "db/down/" + strings.TrimPrefix(up, "db/migrations/")
}

// tableDownSQL reverses tableMigrationSQL so up/down/up cycles pass without a
// hand-written down. Down files run in reverse order, so the table exists.
func tableDownSQL(table Table) string {
	var sql strings.Builder

	fmt.Fprintf(
		&sql,
		`-- Generated by pluto: reverses forced tenant isolation for %[1]s.
`,
		table.Name,
	)

	if table.AppendOnly {
		fmt.Fprintf(
			&sql,
			`DROP TRIGGER IF EXISTS %[1]s_no_delete ON %[1]s;
DROP TRIGGER IF EXISTS %[1]s_no_update ON %[1]s;
DROP FUNCTION IF EXISTS %[1]s_append_only();
`,
			table.Name,
		)
	}

	fmt.Fprintf(
		&sql,
		`DROP POLICY IF EXISTS pluto_tenant_isolation ON %[1]s;
ALTER TABLE %[1]s NO FORCE ROW LEVEL SECURITY;
ALTER TABLE %[1]s DISABLE ROW LEVEL SECURITY;
`,
		table.Name,
	)

	return sql.String()
}

// tableMigrationSQL is safe to apply on a table with partial protection: every
// statement is idempotent. The column is compared as text so uuid and text
// tenant columns both work.
func tableMigrationSQL(table Table) string {
	var sql strings.Builder

	fmt.Fprintf(
		&sql,
		`-- Generated by pluto: forced tenant isolation for %[1]s.
-- The runtime database role must not own this table; owners bypass row
-- level security unless FORCE is set, and superusers always bypass it.
ALTER TABLE %[1]s ENABLE ROW LEVEL SECURITY;
ALTER TABLE %[1]s FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pluto_tenant_isolation ON %[1]s;
CREATE POLICY pluto_tenant_isolation ON %[1]s
    USING (%[2]s::text = current_setting('app.tenant_id', true))
    WITH CHECK (%[2]s::text = current_setting('app.tenant_id', true));
`,
		table.Name,
		table.TenantColumn,
	)

	if !table.AppendOnly {
		return sql.String()
	}

	fmt.Fprintf(
		&sql,
		`
CREATE OR REPLACE FUNCTION %[1]s_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '%[1]s is append-only';
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS %[1]s_no_update ON %[1]s;
CREATE TRIGGER %[1]s_no_update BEFORE UPDATE ON %[1]s
    FOR EACH ROW EXECUTE FUNCTION %[1]s_append_only();
DROP TRIGGER IF EXISTS %[1]s_no_delete ON %[1]s;
CREATE TRIGGER %[1]s_no_delete BEFORE DELETE ON %[1]s
    FOR EACH ROW EXECUTE FUNCTION %[1]s_append_only();
`,
		table.Name,
	)

	return sql.String()
}

// tenantIndexMigrationSQL renders the generated tenant index of the tenant
// root table when a tenant job exists. The policy admits SELECT only while a
// transaction-local switch that nothing but the generated index reader sets
// is on; the security-invoker view exposes the tenant column alone, and the
// reader queries nothing else. There is no BYPASSRLS and no other path.
func tenantIndexMigrationSQL(m Manifest, table Table) string {
	if root, ok := m.TenantRoot(); !ok || root.Name != table.Name ||
		!m.hasEachTenant() {
		return ""
	}

	return fmt.Sprintf(
		`
-- Generated by pluto: the tenant index lists tenant ids for tenant jobs.
DROP POLICY IF EXISTS %[1]s ON %[2]s;
CREATE POLICY %[1]s ON %[2]s FOR SELECT
    USING (current_setting('%[3]s', true) = 'on');
CREATE OR REPLACE VIEW %[4]s WITH (security_invoker = true) AS
    SELECT %[5]s AS tenant_id FROM %[2]s;
`,
		tenantIndexPolicy,
		table.Name,
		tenantIndexSetting,
		tenantIndexView,
		table.TenantColumn,
	)
}

// tenantIndexDownSQL reverses tenantIndexMigrationSQL.
func tenantIndexDownSQL(m Manifest, table Table) string {
	if root, ok := m.TenantRoot(); !ok || root.Name != table.Name ||
		!m.hasEachTenant() {
		return ""
	}

	return fmt.Sprintf(
		"DROP VIEW IF EXISTS %s;\nDROP POLICY IF EXISTS %s ON %s;\n",
		tenantIndexView,
		tenantIndexPolicy,
		table.Name,
	)
}
