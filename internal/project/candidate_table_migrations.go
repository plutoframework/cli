package project

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/plutoframework/cli/internal/sqlcheck"
)

var migrationFilePrefix = regexp.MustCompile(`^(\d+)_`)

// ProposeTableMigrations returns new migration files that give declared
// tables the forced row-level security policy and append-only triggers that
// ARCH612 requires. A table whose existing migrations already satisfy the
// check gets nothing. Applied migrations are never touched: proposals take the
// next free number and are meant to be reviewed and committed like any other
// migration. Tables that no migration creates yet are an error, since a policy
// cannot precede its table.
func ProposeTableMigrations(
	root string,
	m Manifest,
) (map[string][]byte, error) {
	proposals := map[string][]byte{}

	next, err := nextMigrationNumber(root, m)
	if err != nil {
		return nil, err
	}

	tables := append([]Table(nil), m.Tables...)
	sort.Slice(
		tables,
		func(i, j int) bool {
			return tables[i].ID() < tables[j].ID()
		},
	)

	for _, table := range tables {
		cfg := sqlcheck.Config{
			Root:       root,
			SchemaDirs: []string{"db/migrations"},
			Tables: []sqlcheck.Table{{
				Name:         table.Name,
				Group:        table.Group,
				TenantColumn: table.TenantColumn,
				AppendOnly:   table.AppendOnly,
			}},
		}

		found, err := sqlcheck.CheckMigrations(cfg)
		if err != nil {
			return nil, err
		}

		if len(found) == 0 {
			continue
		}

		for _, diagnostic := range found {
			if strings.Contains(diagnostic.Message, "is not created by") ||
				strings.Contains(diagnostic.Message, "no tenant column") {
				return nil, fmt.Errorf(
					"table %s: %s",
					table.ID(),
					diagnostic.Message,
				)
			}
		}

		path := fmt.Sprintf(
			"db/migrations/%03d_rls_%s.sql",
			next,
			table.Name,
		)
		next++

		proposals[path] = []byte(tableMigrationSQL(table))
	}

	return proposals, nil
}

// nextMigrationNumber is one past the highest number on disk or allocated to
// a recorded [migrations.framework] migration, so a proposal never lands on a
// number the framework owns even when that file is not rendered yet.
func nextMigrationNumber(root string, m Manifest) (int, error) {
	entries, err := os.ReadDir(filepath.Join(root, "db/migrations"))
	if err != nil {
		return 0, err
	}

	highest := 0

	for _, number := range m.Migrations.Framework {
		if value, err := strconv.Atoi(number); err == nil && value > highest {
			highest = value
		}
	}

	for _, entry := range entries {
		match := migrationFilePrefix.FindStringSubmatch(entry.Name())
		if match == nil {
			continue
		}

		number, err := strconv.Atoi(match[1])
		if err == nil && number > highest {
			highest = number
		}
	}

	return highest + 1, nil
}

// tableMigrationSQL is safe to apply on a table with partial protection: every
// statement is idempotent. The column is compared as text so uuid and text
// tenant columns both work.
func tableMigrationSQL(table Table) string {
	var sql strings.Builder

	fmt.Fprintf(
		&sql,
		`-- Generated by pluto: forced tenant isolation for %[1]s.
-- The runtime database role must not own this table; owners bypass row
-- level security unless FORCE is set, and superusers always bypass it.
ALTER TABLE %[1]s ENABLE ROW LEVEL SECURITY;
ALTER TABLE %[1]s FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS pluto_tenant_isolation ON %[1]s;
CREATE POLICY pluto_tenant_isolation ON %[1]s
    USING (%[2]s::text = current_setting('app.tenant_id', true))
    WITH CHECK (%[2]s::text = current_setting('app.tenant_id', true));
`,
		table.Name,
		table.TenantColumn,
	)

	if !table.AppendOnly {
		return sql.String()
	}

	fmt.Fprintf(
		&sql,
		`
CREATE OR REPLACE FUNCTION %[1]s_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '%[1]s is append-only';
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS %[1]s_no_update ON %[1]s;
CREATE TRIGGER %[1]s_no_update BEFORE UPDATE ON %[1]s
    FOR EACH ROW EXECUTE FUNCTION %[1]s_append_only();
DROP TRIGGER IF EXISTS %[1]s_no_delete ON %[1]s;
CREATE TRIGGER %[1]s_no_delete BEFORE DELETE ON %[1]s
    FOR EACH ROW EXECUTE FUNCTION %[1]s_append_only();
`,
		table.Name,
	)

	return sql.String()
}
