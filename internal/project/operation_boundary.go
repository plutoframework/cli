package project

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/pelletier/go-toml/v2"
)

// operationBoundaryDiagnostics recognizes the generated operation shape, never
// the mere presence of an authorization call in arbitrary authored control
// flow.
func operationBoundaryDiagnostics(
	root string,
	manifest []byte,
) []ArchitectureDiagnostic {
	diagnostics := []ArchitectureDiagnostic{}
	add := func(id, file string, line int, message, repair string) {
		diagnostics = append(
			diagnostics,
			ArchitectureDiagnostic{
				ID:       id,
				File:     file,
				Line:     line,
				Severity: "error",
				Message:  message,
				Repair:   repair,
			},
		)
	}

	var candidate Manifest

	if err := toml.Unmarshal(manifest, &candidate); err != nil {
		add("ARCH201", "pluto.toml", 1,
			"operation boundary metadata cannot be assessed: "+err.Error(),
			"Repair declarations before selecting a managed boundary mode.")

		return diagnostics
	}

	if candidate.Boundary.Mode == "candidate" {
		return candidateIntegrity(root, candidate)
	}

	m := Manifest{
		Project:      candidate.Project,
		Capabilities: candidate.Capabilities,
		Operations:   candidate.Operations,
		Endpoints:    candidate.Endpoints,
		Jobs:         candidate.Jobs,
		Agents:       candidate.Agents,
	}
	gates := map[string]bool{}
	managed := map[string]bool{}
	authored := map[string]string{}
	declared := map[string]bool{}
	boundaryTypes := map[string]map[string]bool{}
	verify := func(path string, expected []byte) {
		managed[path] = true

		actual, err := os.ReadFile(
			filepath.Join(root, filepath.FromSlash(path)),
		)
		if err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				"required managed boundary is absent: "+path,
				"Explicitly migrate authored business bodies behind declared "+
					"managed operation/entry adapters; preserve authored "+
					"logic.",
			)

			return
		}

		if !Equivalent(actual, expected) {
			add(
				"ARCH202",
				path,
				1,
				"managed operation or entry adapter differs from its "+
					"declared contract",
				"Restore the canonical managed boundary; keep business "+
					"orchestration only in the private operation "+
					"implementation.",
			)
		}
	}
	generatedSource := func(
		template string,
		data templateData,
	) (
		[]byte,
		error,
	) {
		source, err := render(template, data)

		return append(
			[]byte("// Code generated by pluto; DO NOT EDIT.\n"),
			source...), err
	}
	validOperations := []Operation{}

	for _, operation := range m.Operations {
		endpoint := operation.Endpoint()
		if err := operation.Validate(
			m.Capabilities.Tenancy == "multi",
		); err != nil {
			add(

				"ARCH201",

				"pluto.toml",

				1,

				"declared operation cannot establish a supported gate: "+
					err.Error(),

				"Declare valid independent operation identity, authority and "+
					"contracts.",
			)

			continue
		}

		validOperations = append(validOperations, operation)
		dir := "internal/operations/" + operation.Group
		declared[dir] = true

		operationImport := m.Project.Module + "/" + dir
		if boundaryTypes[operationImport] == nil {
			boundaryTypes[operationImport] = map[string]bool{}
		}

		boundaryTypes[operationImport][operation.Action] = true
		boundaryTypes[operationImport][operation.Action+"Boundary"] = true
		authored[dir+"/"+strings.ToLower(
			operation.Action,
		)+".go"] = operation.Action
		path := dir + "/" + strings.ToLower(operation.Action) + "_gate_gen.go"
		gates[path] = true

		source, err := generatedSource(
			"operation_gate.go",
			dataFor(m, endpoint),
		)
		if err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				err.Error(),
				"Repair operation metadata.",
			)

			continue
		}

		verify(path, source)
	}

	m.Operations = validOperations
	validEndpoints := []Endpoint{}

	for _, entry := range m.Endpoints {
		endpoint, err := m.OperationEndpoint(entry)
		if err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				err.Error(),
				"Declare an independent operation and reference it from the "+
					"HTTP entry.",
			)

			continue
		}

		validEndpoints = append(validEndpoints, endpoint)

		imported := m.Project.Module + "/internal/handlers/" + endpoint.Group
		if boundaryTypes[imported] == nil {
			boundaryTypes[imported] = map[string]bool{}
		}

		boundaryTypes[imported][endpoint.Action+"Operations"] = true

		source, err := generatedSource("handler.go", dataFor(m, endpoint))
		if err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				err.Error(),
				"Repair HTTP entry metadata.",
			)

			continue
		}

		verify(
			"internal/handlers/"+endpoint.Group+"/"+strings.ToLower(
				endpoint.Action,
			)+".go",
			source,
		)
	}

	m.Endpoints = validEndpoints
	if m.Project.Module != "" {
		source, err := generatedSource(
			"authorization.go",
			dataFor(m, Endpoint{}),
		)
		if err == nil {
			verify("internal/access/authorization_gen.go", source)
		}

		expected, err := Managed(m)
		if err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				"managed entry registration cannot be derived: "+err.Error(),
				"Declare every worker/tool target operation before "+
					"generating its managed adapter.",
			)
		} else {
			for path, source := range expected {
				isRegistry := path == "internal/app/routes_gen.go" ||
					strings.HasPrefix(path, "internal/handlers/") &&
						strings.HasSuffix(path, "/register_gen.go")
				isWorker := path == "internal/app/worker_runtime_gen.go" ||
					strings.HasPrefix(path, "internal/background/") ||
					strings.HasPrefix(path, "internal/jobs/") ||
					strings.HasPrefix(path, "internal/jobcontracts/")

				isAgent := strings.HasPrefix(path, "internal/agents/")
				if isRegistry || isWorker || isAgent {
					verify(path, source)
				}
			}
		}
	}

	undeclared := map[string]bool{}
	sources := []operationBoundarySource{}
	packageNames := map[string]string{}
	directories := inspectionDirectories(root, m.Project.Module, nil)

	walkErr := filepath.WalkDir(
		root,
		func(
			path string,
			entry fs.DirEntry,
			err error,
		) error {
			if err != nil {
				return err
			}

			relative, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}

			relative = filepath.ToSlash(relative)
			if entry.IsDir() {
				if skipInspectionDirectory(
					relative,
					entry.Name(),
					directories,
				) {
					return filepath.SkipDir
				}

				if relative != "." {
					if _, err := os.Stat(
						filepath.Join(
							path,
							"go.mod",
						),
					); err == nil {
						return filepath.SkipDir
					}
				}

				return nil
			}

			if !strings.HasSuffix(relative, ".go") ||
				strings.HasSuffix(relative, "_test.go") ||
				entry.Type()&os.ModeSymlink != 0 {
				return nil
			}

			set := token.NewFileSet()

			tree, err := parser.ParseFile(set, path, nil, parser.AllErrors)
			if err != nil {
				add(
					"ARCH201",
					relative,
					1,
					"operation source cannot be assessed: "+err.Error(),
					"Repair Go syntax before inspecting managed boundary "+
						"ownership.",
				)

				return nil
			}

			dir := filepath.ToSlash(filepath.Dir(relative))

			namespace := m.Project.Module
			if dir != "." {
				namespace += "/" + dir
			}

			sources = append(
				sources,
				operationBoundarySource{
					relative,
					dir,
					namespace,
					set,
					tree,
				},
			)
			packageNames[namespace] = tree.Name.Name

			return nil
		},
	)
	if walkErr != nil {
		add("ARCH201", ".", 1,
			fmt.Sprintf("operation boundary inventory incomplete: %v", walkErr),
			"Restore source access and rerun the canonical inspection.")
	}

	aliases := map[string][]operationBoundaryAlias{}

	for _, source := range sources {
		imports := operationBoundaryImports(source.tree, packageNames)
		for _, declaration := range source.tree.Decls {
			group, ok := declaration.(*ast.GenDecl)
			if !ok || group.Tok != token.TYPE {
				continue
			}

			for _, item := range group.Specs {
				spec, ok := item.(*ast.TypeSpec)
				if !ok {
					continue
				}

				key := source.namespace + "." + spec.Name.Name
				aliases[key] = append(aliases[key], operationBoundaryAlias{
					source.namespace, spec.Type, imports,
				})
			}
		}
	}

	for _, source := range sources {
		relative, dir := source.relative, source.dir
		set, tree := source.set, source.tree

		inOperations := dir == "internal/operations" ||
			strings.HasPrefix(dir, "internal/operations/")
		if inOperations && !declared[dir] && !undeclared[dir] {
			for _, decl := range tree.Decls {
				if _, ok := decl.(*ast.FuncDecl); ok {
					add(
						"ARCH201",
						relative,
						1,
						"production operation package has no declared "+
							"managed operation boundary: "+dir,
						"Inventory its entry operations in endpoint "+
							"metadata and explicitly migrate them "+
							"behind managed gates; legacy authored "+
							"authorization calls are not proof of a "+
							"mandatory boundary.",
					)

					undeclared[dir] = true

					break
				}
			}
		}

		imports := map[string]string{}

		for _, spec := range tree.Imports {
			value, _ := strconv.Unquote(spec.Path.Value)

			name := filepath.Base(value)
			if actual := packageNames[value]; actual != "" {
				name = actual
			}

			if spec.Name != nil {
				name = spec.Name.Name
			}

			imports[name] = value
			if name == "." &&
				strings.HasPrefix(
					value,
					m.Project.Module+"/internal/operations/",
				) {
				add(
					"ARCH204",
					relative,
					set.Position(spec.Pos()).Line,
					"dot-imported operation boundary hides its qualified "+
						"ownership",
					"Use a qualified managed boundary; production dot "+
						"imports are unsupported for operation gates.",
				)
			}
		}

		boundaryName := func(expression ast.Expr) bool {
			return isOperationBoundaryType(expression, source.namespace,
				imports, boundaryTypes, aliases, map[string]bool{})
		}
		allowedDeclaration := token.NoPos

		if inOperations && declared[dir] && !gates[relative] {
			for _, decl := range tree.Decls {
				function, ok := decl.(*ast.FuncDecl)
				if !ok {
					continue
				}

				expected := authored[relative]
				if function.Name.Name == "execute" && expected != "" &&
					receiverName(function.Recv) == expected {
					allowedDeclaration = function.Name.Pos()
					continue
				}

				if function.Recv != nil ||
					ast.IsExported(function.Name.Name) {
					add(
						"ARCH204",
						relative,
						set.Position(function.Pos()).Line,
						"unsupported operation entry or receiver method "+
							"outside the managed gate: "+function.Name.Name,
						"Expose only the generated Execute gate; keep "+
							"private implementation and package "+
							"helpers behind it. Additional use cases "+
							"require declared operation boundaries.",
					)
				}
			}
		}

		if inOperations && declared[dir] && !gates[relative] {
			for _, decl := range tree.Decls {
				group, ok := decl.(*ast.GenDecl)
				if !ok || group.Tok != token.VAR {
					continue
				}

				for _, spec := range group.Specs {
					value, ok := spec.(*ast.ValueSpec)
					if !ok {
						continue
					}

					for _, name := range value.Names {
						if ast.IsExported(name.Name) {
							add(
								"ARCH204",
								relative,
								set.Position(name.Pos()).Line,
								"exported operation variable creates an "+
									"unsupported entry or mutable "+
									"global: "+name.Name,
								"Keep operation entry points managed; "+
									"inject typed dependencies "+
									"instead of exporting callable "+
									"or mutable globals.",
							)
						}
					}
				}
			}
		}

		if managed[relative] {
			continue
		}

		ast.Inspect(tree, func(node ast.Node) bool {
			switch n := node.(type) {
			case *ast.Ident:
				if inOperations && declared[dir] && n.Name == "execute" &&
					n.Pos() != allowedDeclaration {
					add(
						"ARCH203",
						relative,
						set.Position(n.Pos()).Line,
						"private operation implementation referenced "+
							"outside its managed gate",
						"Call the managed Execute method; do not capture,"+
							" alias, recurse into or invoke the "+
							"private implementation from helpers.",
					)
				}
			case *ast.StructType:
				for _, field := range n.Fields.List {
					if len(field.Names) == 0 && boundaryName(field.Type) {
						add(
							"ARCH204",
							relative,
							set.Position(field.Pos()).Line,
							"embedding an operation gate or sealed "+
								"boundary can override its entry "+
								"method",
							"Inject the generated boundary as a named "+
								"field or constructor dependency; do "+
								"not embed it in production adapters.",
						)
					}
				}

			case *ast.InterfaceType:
				for _, field := range n.Methods.List {
					if len(field.Names) == 0 && boundaryName(field.Type) {
						add(
							"ARCH204",
							relative,
							set.Position(field.Pos()).Line,
							"embedding a managed operation boundary into "+
								"another interface is unsupported",
							"Use the generated sealed contract directly; "+
								"do not create a replacement "+
								"interface embedding route.",
						)
					}
				}

			case *ast.TypeSpec:
				if boundaryName(n.Type) {
					add(
						"ARCH204",
						relative,
						set.Position(n.Pos()).Line,
						"aliasing or redefining an operation boundary "+
							"outside managed code is unsupported",
						"Use the generated sealed entry contract "+
							"directly; aliases cannot establish "+
							"another authorized implementation.",
					)
				}
			}

			return true
		})
	}

	return diagnostics
}

func receiverName(fields *ast.FieldList) string {
	if fields == nil || len(fields.List) != 1 {
		return ""
	}

	expression := fields.List[0].Type
	if pointer, ok := expression.(*ast.StarExpr); ok {
		expression = pointer.X
	}

	name, _ := expression.(*ast.Ident)
	if name == nil {
		return ""
	}

	return name.Name
}

func unwrapBoundaryType(expression ast.Expr) ast.Expr {
	switch value := expression.(type) {
	case *ast.StarExpr:
		return unwrapBoundaryType(value.X)
	case *ast.ParenExpr:
		return unwrapBoundaryType(value.X)
	case *ast.IndexExpr:
		return unwrapBoundaryType(value.X)
	case *ast.IndexListExpr:
		return unwrapBoundaryType(value.X)
	}

	return expression
}

type operationBoundarySource struct {
	relative, dir, namespace string
	set                      *token.FileSet
	tree                     *ast.File
}

type operationBoundaryAlias struct {
	namespace  string
	expression ast.Expr
	imports    map[string]string
}

func operationBoundaryImports(
	tree *ast.File,
	packages map[string]string,
) map[string]string {
	imports := map[string]string{}

	for _, spec := range tree.Imports {
		path, _ := strconv.Unquote(spec.Path.Value)

		name := packages[path]
		if name == "" {
			name = filepath.Base(path)
		}

		if spec.Name != nil {
			name = spec.Name.Name
		}

		imports[name] = path
	}

	return imports
}

func isOperationBoundaryType(expression ast.Expr, namespace string,
	imports map[string]string, known map[string]map[string]bool,
	aliases map[string][]operationBoundaryAlias, seen map[string]bool,
) bool {
	expression = unwrapBoundaryType(expression)
	name := ""

	switch value := expression.(type) {
	case *ast.Ident:
		name = value.Name
	case *ast.SelectorExpr:
		qualifier, ok := value.X.(*ast.Ident)
		if !ok {
			return false
		}

		namespace = imports[qualifier.Name]
		if namespace == "" {
			return false
		}

		name = value.Sel.Name
	case *ast.InterfaceType:
		for _, field := range value.Methods.List {
			if len(
				field.Names,
			) == 0 &&
				isOperationBoundaryType(
					field.Type,
					namespace,

					imports,
					known,
					aliases,
					seen,
				) {
				return true
			}
		}

		return false
	case *ast.StructType:
		for _, field := range value.Fields.List {
			if len(
				field.Names,
			) == 0 &&
				isOperationBoundaryType(
					field.Type,
					namespace,

					imports,
					known,
					aliases,
					seen,
				) {
				return true
			}
		}

		return false
	default:
		return false
	}

	if known[namespace][name] {
		return true
	}

	key := namespace + "." + name
	if seen[key] {
		return false
	}

	seen[key] = true
	defer delete(seen, key)

	for _, alias := range aliases[key] {
		if isOperationBoundaryType(alias.expression, alias.namespace,
			alias.imports, known, aliases, seen) {
			return true
		}
	}

	return false
}
