package project

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/pelletier/go-toml/v2"
)

// operationBoundaryDiagnostics recognizes the generated operation shape, never
// the mere presence of an authorization call in arbitrary authored control flow.
func operationBoundaryDiagnostics(
	root string,
	manifest []byte,
) []ArchitectureDiagnostic {
	diagnostics := []ArchitectureDiagnostic{}
	add := func(id, file string, line int, message, repair string) {
		diagnostics = append(
			diagnostics,
			ArchitectureDiagnostic{
				ID:       id,
				File:     file,
				Line:     line,
				Severity: "error",
				Message:  message,
				Repair:   repair,
			},
		)
	}

	var declaration struct {
		Project      Project      `toml:"project"`
		Capabilities Capabilities `toml:"capabilities"`
		Endpoints    []Endpoint   `toml:"endpoints"`
	}
	if err := toml.Unmarshal(manifest, &declaration); err != nil {
		add(
			"ARCH201",
			"pluto.toml",
			1,
			"operation boundary metadata cannot be assessed: "+err.Error(),
			"Repair operation metadata and explicitly migrate authored implementations; no authorization guarantee is inferred.",
		)
	}

	m := Manifest{
		Project:      declaration.Project,
		Capabilities: declaration.Capabilities,
		Endpoints:    declaration.Endpoints,
	}
	gates := map[string]bool{}
	managed := map[string]bool{}
	authored := map[string]string{}
	declared := map[string]bool{}
	boundaryTypes := map[string]map[string]bool{}
	validEndpoints := []Endpoint{}

	for _, endpoint := range m.Endpoints {
		if !packageName.MatchString(endpoint.Group) ||
			!actionName.MatchString(endpoint.Action) ||
			m.Project.Module == "" {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				"declared operation has unsupported boundary metadata",
				"Declare a valid group, action and module before generating the managed boundary.",
			)

			continue
		}

		if err := endpoint.Validate(
			m.Capabilities.Tenancy == "multi",
		); err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				"declared operation cannot establish a supported gate: "+err.Error(),
				"Declare complete valid operation metadata, including an explicit permission for protected writes.",
			)

			continue
		}

		validEndpoints = append(validEndpoints, endpoint)
		dir := "internal/operations/" + endpoint.Group
		declared[dir] = true
		operationImport := m.Project.Module + "/" + dir
		handlerImport := m.Project.Module + "/internal/handlers/" + endpoint.Group

		if boundaryTypes[operationImport] == nil {
			boundaryTypes[operationImport] = map[string]bool{}
		}

		if boundaryTypes[handlerImport] == nil {
			boundaryTypes[handlerImport] = map[string]bool{}
		}

		boundaryTypes[operationImport][endpoint.Action] = true
		boundaryTypes[operationImport][endpoint.Action+"Boundary"] = true
		boundaryTypes[handlerImport][endpoint.Action+"Operations"] = true

		authored[dir+"/"+strings.ToLower(endpoint.Action)+".go"] = endpoint.Action
		for _, item := range []struct{ directory, template, suffix string }{{"operations", "operation_gate.go", "_gate_gen.go"}, {"handlers", "handler.go", ".go"}} {
			path := filepath.ToSlash(
				filepath.Join(
					"internal",
					item.directory,
					endpoint.Group,
					strings.ToLower(endpoint.Action)+item.suffix,
				),
			)

			managed[path] = true
			if item.directory == "operations" {
				gates[path] = true
			}

			source, err := render(item.template, dataFor(m, endpoint))
			if err != nil {
				add(
					"ARCH201",
					"pluto.toml",
					1,
					"operation boundary cannot be rendered for "+path+": "+err.Error(),
					"Repair metadata before generating the managed gate.",
				)

				continue
			}

			expected := append(
				[]byte("// Code generated by pluto; DO NOT EDIT.\n"),
				source...)

			actual, err := os.ReadFile(
				filepath.Join(root, filepath.FromSlash(path)),
			)
			if err != nil {
				add(
					"ARCH201",
					"pluto.toml",
					1,
					"required managed operation boundary is absent: "+path,
					"Explicitly migrate the authored operation to private execute, retain typed dependencies, then generate the managed gate and sealed handler. Do not overwrite authored business code.",
				)

				continue
			}

			if !Equivalent(actual, expected) {
				add(
					"ARCH202",
					path,
					1,
					"managed operation gate or sealed entry adapter differs from its declared contract",
					"Restore the canonical managed boundary; keep business orchestration in the private authored execute method.",
				)
			}
		}
	}

	m.Endpoints = validEndpoints
	if m.Project.Module != "" {
		path := "internal/access/authorization_gen.go"
		managed[path] = true

		source, err := render("authorization.go", dataFor(m, Endpoint{}))
		if err == nil {
			actual, readErr := os.ReadFile(
				filepath.Join(root, filepath.FromSlash(path)),
			)
			if readErr != nil {
				add(
					"ARCH201",
					"pluto.toml",
					1,
					"required current-assignment authorization adapter is absent: "+path,
					"Explicitly migrate composition to a current membership resolver and regenerate the managed adapter.",
				)
			} else if !Equivalent(actual, append([]byte("// Code generated by pluto; DO NOT EDIT.\n"), source...)) {
				add(
					"ARCH202",
					path,
					1,
					"managed current-assignment authorization adapter differs from its declared contract",
					"Restore the managed adapter; role snapshots supplied by callers must not substitute for current membership resolution.",
				)
			}
		}
	}

	if m.Project.Module != "" {
		expected, err := Managed(m)
		if err != nil {
			add(
				"ARCH201",
				"pluto.toml",
				1,
				"managed operation entry registration cannot be derived: "+err.Error(),
				"Repair declarations and explicitly regenerate entry registration.",
			)
		} else {
			for path, source := range expected {
				isGroupRegistry := strings.HasPrefix(
					path,
					"internal/handlers/",
				) &&
					strings.HasSuffix(path, "/register_gen.go")
				if path != "internal/app/routes_gen.go" && !isGroupRegistry {
					continue
				}

				managed[path] = true

				actual, err := os.ReadFile(
					filepath.Join(root, filepath.FromSlash(path)),
				)
				if err != nil {
					add(
						"ARCH201",
						"pluto.toml",
						1,
						"required managed operation entry registration is absent: "+path,
						"Explicitly migrate entry registration with the declared managed gates.",
					)
				} else if !Equivalent(actual, source) {
					add(
						"ARCH202",
						path,
						1,
						"managed operation entry registration differs from its declared contract",
						"Restore managed entry registration; application composition may inject gate dependencies but must not replace declared entry dispatch.",
					)
				}
			}
		}
	}

	undeclared := map[string]bool{}

	walkErr := filepath.WalkDir(
		root,
		func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}

			relative, _ := filepath.Rel(root, path)
			relative = filepath.ToSlash(relative)

			if entry.IsDir() {
				switch entry.Name() {
				case ".git", "node_modules", "vendor", "testdata", "dist":
					return filepath.SkipDir
				}

				if relative != "." {
					if _, err := os.Stat(
						filepath.Join(path, "go.mod"),
					); err == nil {
						return filepath.SkipDir
					}
				}

				return nil
			}

			if !strings.HasSuffix(relative, ".go") ||
				strings.HasSuffix(relative, "_test.go") ||
				entry.Type()&os.ModeSymlink != 0 {
				return nil
			}

			set := token.NewFileSet()

			tree, err := parser.ParseFile(set, path, nil, parser.AllErrors)
			if err != nil {
				return nil
			}

			dir := filepath.ToSlash(filepath.Dir(relative))

			inOperations := dir == "internal/operations" ||
				strings.HasPrefix(dir, "internal/operations/")
			if inOperations && !declared[dir] && !undeclared[dir] {
				for _, decl := range tree.Decls {
					if _, ok := decl.(*ast.FuncDecl); ok {
						add(
							"ARCH201",
							relative,
							1,
							"production operation package has no declared managed operation boundary: "+dir,
							"Inventory its entry operations in endpoint metadata and explicitly migrate them behind managed gates; legacy authored authorization calls are not proof of a mandatory boundary.",
						)

						undeclared[dir] = true

						break
					}
				}
			}

			imports := map[string]string{}

			for _, spec := range tree.Imports {
				value, _ := strconv.Unquote(spec.Path.Value)

				name := filepath.Base(value)
				if spec.Name != nil {
					name = spec.Name.Name
				}

				imports[name] = value
				if name == "." &&
					strings.HasPrefix(
						value,
						m.Project.Module+"/internal/operations/",
					) {
					add(
						"ARCH204",
						relative,
						set.Position(spec.Pos()).Line,
						"dot-imported operation boundary hides its qualified ownership",
						"Use a qualified managed boundary; production dot imports are unsupported for operation gates.",
					)
				}
			}

			boundaryName := func(expression ast.Expr) bool {
				expression = unwrapBoundaryType(expression)

				selector, ok := expression.(*ast.SelectorExpr)
				if !ok {
					return false
				}

				qualifier, ok := selector.X.(*ast.Ident)
				if !ok {
					return false
				}

				imported := imports[qualifier.Name]

				return boundaryTypes[imported][selector.Sel.Name]
			}
			allowedDeclaration := token.NoPos

			if inOperations && declared[dir] && !gates[relative] {
				for _, decl := range tree.Decls {
					function, ok := decl.(*ast.FuncDecl)
					if !ok {
						continue
					}

					expected := authored[relative]
					if function.Name.Name == "execute" && expected != "" &&
						receiverName(function.Recv) == expected {
						allowedDeclaration = function.Name.Pos()
						continue
					}

					if function.Recv != nil ||
						ast.IsExported(function.Name.Name) {
						add(
							"ARCH204",
							relative,
							set.Position(function.Pos()).Line,
							"unsupported operation entry or receiver method outside the managed gate: "+function.Name.Name,
							"Expose only the generated Execute gate; keep private implementation and package helpers behind it. Additional use cases require declared operation boundaries.",
						)
					}
				}
			}

			if inOperations && declared[dir] && !gates[relative] {
				for _, decl := range tree.Decls {
					group, ok := decl.(*ast.GenDecl)
					if !ok || group.Tok != token.VAR {
						continue
					}

					for _, spec := range group.Specs {
						value, ok := spec.(*ast.ValueSpec)
						if !ok {
							continue
						}

						for _, name := range value.Names {
							if ast.IsExported(name.Name) {
								add(
									"ARCH204",
									relative,
									set.Position(name.Pos()).Line,
									"exported operation variable creates an unsupported entry or mutable global: "+name.Name,
									"Keep operation entry points managed; inject typed dependencies instead of exporting callable or mutable globals.",
								)
							}
						}
					}
				}
			}

			if managed[relative] {
				return nil
			}

			ast.Inspect(tree, func(node ast.Node) bool {
				switch n := node.(type) {
				case *ast.Ident:
					if inOperations && declared[dir] && n.Name == "execute" &&
						n.Pos() != allowedDeclaration {
						add(
							"ARCH203",
							relative,
							set.Position(n.Pos()).Line,
							"private operation implementation referenced outside its managed gate",
							"Call the managed Execute method; do not capture, alias, recurse into or invoke the private implementation from helpers.",
						)
					}
				case *ast.StructType:
					for _, field := range n.Fields.List {
						if len(field.Names) == 0 && boundaryName(field.Type) {
							add(
								"ARCH204",
								relative,
								set.Position(field.Pos()).Line,
								"embedding an operation gate or sealed boundary can override its entry method",
								"Inject the generated boundary as a named field or constructor dependency; do not embed it in production adapters.",
							)
						}
					}

				case *ast.InterfaceType:
					for _, field := range n.Methods.List {
						if len(field.Names) == 0 && boundaryName(field.Type) {
							add(
								"ARCH204",
								relative,
								set.Position(field.Pos()).Line,
								"embedding a managed operation boundary into another interface is unsupported",
								"Use the generated sealed contract directly; do not create a replacement interface embedding route.",
							)
						}
					}

				case *ast.TypeSpec:
					if boundaryName(n.Type) {
						add(
							"ARCH204",
							relative,
							set.Position(n.Pos()).Line,
							"aliasing or redefining an operation boundary outside managed code is unsupported",
							"Use the generated sealed entry contract directly; aliases cannot establish another authorized implementation.",
						)
					}
				}

				return true
			})

			return nil
		},
	)
	if walkErr != nil {
		add(
			"ARCH201",
			".",
			1,
			fmt.Sprintf("operation boundary inventory incomplete: %v", walkErr),
			"Restore source access and rerun the canonical inspection.",
		)
	}

	return diagnostics
}

func receiverName(fields *ast.FieldList) string {
	if fields == nil || len(fields.List) != 1 {
		return ""
	}

	expression := fields.List[0].Type
	if pointer, ok := expression.(*ast.StarExpr); ok {
		expression = pointer.X
	}

	name, _ := expression.(*ast.Ident)
	if name == nil {
		return ""
	}

	return name.Name
}

func unwrapBoundaryType(expression ast.Expr) ast.Expr {
	switch value := expression.(type) {
	case *ast.StarExpr:
		return unwrapBoundaryType(value.X)
	case *ast.ParenExpr:
		return unwrapBoundaryType(value.X)
	}

	return expression
}
